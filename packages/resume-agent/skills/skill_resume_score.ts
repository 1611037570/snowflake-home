export const resumeScore = (): Skill => ({
  id: "resume_score",
  completionPolicy: { requiredEvidence: ["read"] }, // 评分必须基于真实读取的简历。
  role: "task" as const, // 参与任务契约规划的任务能力。
  name: "AI 简历评估",
  description: `对简历做全方位综合评估：先体检，再从信息完整度、阅读效率、职业契合度、职业成就、发展潜力与职业稳定性六个维度打分并给出改进建议。`,
  instructions: `# 评估范围
先读取简历，评估文本内容、结构和时间线；工具未提供页面渲染，不能评价字体、颜色或分页。仅依据简历与用户提供的岗位信息判断，不推测候选人的真实能力。

# 六维评分
固定顺序：信息完整度、阅读效率、职业契合度、职业成就、发展潜力、职业稳定性。每项给出 0～100 的整数分、具体依据和主要缺口；确实不适用或缺少判断基础时标记“不适用”。总分为有效分数的算术平均值并四舍五入。
- 信息完整度：目标岗位与当前职业阶段所需的信息、经历细节及时间线是否充分；并行经历不因日期重叠直接判错。
- 阅读效率：重点是否易找，描述是否清楚、紧凑且无重复；不以字数或术语多少直接打分。
- 职业契合度：岗位要求能否从经历和技能中找到证据；岗位不明确时说明判断局限，不能用行业惯例代替岗位要求。
- 职业成就：区分个人行动与团队结果；数字需有可核对的背景，非量化成果也可作为证据。
- 发展潜力：关注职责成长、学习迁移与解决问题的证据，不凭学校或企业名气推断。
- 职业稳定性：结合经历性质、职业阶段与任职时间判断；学生、无适用任职记录或依据不足时不评分，不猜测离职原因。

# 建议与输出
检查错别字、矛盾、空洞表述和关键事实缺口，按对求职判断的影响排序。每项建议说明具体问题、依据和下一步行动；区分可直接修改与需要用户补充的事实。敏感属性不参与评分，联系方式只检查是否存在，不复述具体值。输出总分、六维依据、问题清单和优先处理的建议；不强制固定标题或篇幅。`,
});
